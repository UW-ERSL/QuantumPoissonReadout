"""makeTables.py -- every table of the paper, written to tables/ as LaTeX.

    python makeTables.py            all six tables (about 30 seconds)
    python makeTables.py qiskit     just that one
    python makeTables.py --list     names and destinations

Each file holds only the `tabular`, so the surrounding `table` environment, the caption and the label
stay in the paper. Every claim the text makes about a table is asserted before the table is written,
and the values the text quotes are printed after each table. sigma_max = 1, readout tolerance
eps = 1e-2 and polynomial tolerance eps_p = eps / 3 unless stated.
"""
import os
import sys

import numpy as np

from quantumpoissonreadout import (Cell, GEOMETRIES, sigma_fe, ls_exact, ls_poly, qiskit_readout,
                                   arithmetic_readout, amplitude_estimation, ls_cost, baseline_cost)

TABDIR = "tables"
EPS = 1e-2
EPS_P = EPS / 3


def write(name, spec, header, rows):
    os.makedirs(TABDIR, exist_ok=True)
    out = ["% generated by makeTables.py -- do not edit", f"\\begin{{tabular}}{{{spec}}}", "\\toprule",
           " & ".join(header) + r"\\", "\\midrule"]
    out += [" & ".join(str(c) for c in r) + r"\\" for r in rows]
    out += ["\\bottomrule", "\\end{tabular}", ""]
    open(f"{TABDIR}/{name}.tex", "w").write("\n".join(out))
    print(f"    {TABDIR}/{name}.tex")


def sci(x, digits=2):
    """$a.b \\times 10^{e}$ with `digits` significant digits."""
    e = int(np.floor(np.log10(abs(x))))
    m = round(x / 10 ** e, digits - 1)
    if abs(m) >= 10:
        m, e = m / 10, e + 1
    return f"${m:.{digits - 1}f} \\times 10^{{{e}}}$"


def intx(x):
    return f"${int(x):,}$".replace(",", "{,}")


def fx(x, digits=4):
    return f"${x:.{digits}f}$"


# ---- tab:ls (Sec. 5.1): the least-squares form on three cells ----------------------------------
def tab_ls(N=256):
    rows = []
    for name in GEOMETRIES:
        for rho in (10.0, 1e4):
            c = Cell(name, N, rho)
            fe, ls = sigma_fe(c), ls_exact(c)
            est, d, e = ls_poly(c, EPS_P)
            assert abs(ls - fe) <= 1e-12 * fe, (name, rho)                  # "agree to rounding"
            assert c.reuss * (1 - 1e-12) <= fe <= c.sbar, (name, rho)      # between the bounds
            assert abs(est - fe) <= e * c.sbar, (name, rho)                 # Prop. readout
            if name == "laminate":
                assert abs(fe - c.reuss) <= 1e-12 * fe                     # series layers: Reuss
            rows.append([name, f"${rho:g}$" if rho < 100 else "$10^{4}$", f"${d}$",
                         sci(c.reuss, 3), sci(fe, 5), sci(c.sbar, 3),
                         sci(max(abs(ls - fe) / fe, 1e-17), 1), sci((est - fe) / c.sbar, 2)])
            print(f"       {name:8s} rho {rho:g}: sigma^H {fe:.6e}, LS rel {abs(ls - fe) / fe:.1e}, "
                  f"poly/sbar {(est - fe) / c.sbar:.2e}, sbar/sigma^H {c.sbar / fe:.1f}")
    write("ls", "lrrrrrrr",
          ["cell", r"$\rho$", "$d_f$", "Reuss", r"$\sigma^H_{xx}$", r"$\bar\sigma$",
           "least squares", "estimate"], rows)


# ---- tab:mesh (Sec. 5.2): mesh independence, square ---------------------------------------------
def tab_mesh(Ns=(16, 64, 256, 1024), rho=10.0):
    rows = []
    for N in Ns:
        c = Cell("square", N, rho)
        fe = sigma_fe(c)
        est, d, e = ls_poly(c, EPS_P)
        assert d == 20 and abs(est - fe) <= e * c.sbar, N
        rows.append([f"${N}$", intx(N * N), f"${d}$", fx(fe, 6), fx(est, 6), sci((est - fe) / c.sbar, 2)])
        print(f"       N = {N}: sigma^H {fe:.6f}, estimate {est:.6f}, (est - fe)/sbar {(est - fe) / c.sbar:.2e}")
    write("mesh", "rrrrrr", ["$N$", r"$N_{\mathrm{dof}}$", "$d_f$", r"$\sigma^H_{xx}$",
                                     "estimate", "error"], rows)


# ---- tab:qiskit (Sec. 5.3): the readout as one Qiskit circuit --------------------------------------
def tab_qiskit(Ns=(4, 8), rho=10.0):
    rows = []
    for N in Ns:
        r = qiskit_readout(N, rho, EPS)
        assert r["phase_err"] < 1e-12 and r["A_imag"] < 1e-13
        assert abs(r["estimate"] - r["poly"]) < 1e-12, N                  # circuit = polynomial
        assert abs(r["ls"] - r["fe"]) < 1e-14 and abs(r["estimate"] - r["fe"]) <= r["e_t"] * r["sbar"]
        rows.append([f"${N}$", f"${r['qubits']}$", f"${r['d']}$", intx(r["cx_UVs"]), intx(r["cx"]),
                     intx(r["oneq"]), intx(r["depth"]), fx(r["A"], 6), fx(r["estimate"], 6),
                     fx(r["fe"], 6), sci((r["estimate"] - r["fe"]) / r["sbar"], 2)])
        print(f"       N = {N}: |estimate - polynomial| {abs(r['estimate'] - r['poly']):.1e}, "
              f"phase error {r['phase_err']:.1e}, e_t {r['e_t']:.2e}, imag A {r['A_imag']:.1e}")
    write("qiskit", "rrrrrrrrrrr",
          ["$N$", "qubits", "$d_f$", r"CX, $\mathcal{U}_{V\Sigma}$", "CX", "1-qubit", "depth", "$A$",
           "estimate", r"$\sigma^H_{xx}$", "error"], rows)


# ---- tab:arith (Sec. 5.4): gate-level arithmetic, encoding error through the circuit ----------------
def tab_arith(Ns=(4, 8), Fs=(12, 16, 20, 24)):
    rows = []
    for N in Ns:
        ratios = []
        for F in Fs:
            r = arithmetic_readout(N, F=F)
            gap = abs(r["A_gate"] - r["A_exact"])
            ratios.append(gap / r["bound"])
            assert gap <= r["bound"], (N, F)                                 # Lemma propagation
            assert gap <= r["bound"] / 2300, (N, F)                          # "a factor of at least 2.3e3"
            rows.append([f"${N}$", f"${F}$", sci(r["delta"]), sci(gap), sci(r["bound"])])
        print(f"       N = {N}: largest gap/bound {max(ratios):.1e}")
    write("arith", "rrrrr", ["$N$", "$F$", r"$\delta$", r"$\abs{A - A_{\mathrm{ex}}}$",
                                     r"$\bar\sigma\, d_f\,\delta$"], rows)


# ---- tab:ae (Sec. 5.4): amplitude estimation ---------------------------------------------------------
def tab_ae(cases=((4, 1e-2), (8, 1e-2), (8, 1e-3)), runs=20_000, seed=1):
    rows = []
    for N, eps in cases:
        r = arithmetic_readout(N, eps=eps)
        M = int(np.ceil(3 * np.pi * (1 + r["e_t"]) / (eps * r["sbar"])))
        Ah = amplitude_estimation(r["A_gate"], M, runs, seed)
        s = (1 + r["e_t"]) * Ah - r["e_t"] * r["sbar"]
        p_amp = np.mean(np.abs(Ah - r["A_gate"]) <= np.pi / M)
        p_err = np.mean(np.abs(s - r["fe"]) <= eps * r["sbar"])
        assert p_amp >= 8 / np.pi ** 2 and p_err >= p_amp, (N, eps)
        rows.append([f"${N}$", sci(eps, 1).replace("1.0 \\times ", ""), f"${r['d']}$", f"${r['F']}$",
                     intx(M), sci((2 * M - 1) * r["d"]), fx(p_amp, 3), fx(p_err, 3)])
        grid = np.arcsin(r["A_gate"]) / np.pi * M
        print(f"       N = {N}, eps = {eps:g}: M = {M}, P(amp) {p_amp:.3f}, P(err) {p_err:.3f}, "
              f"distance of M theta / pi from the grid {abs(grid - round(grid)):.3f}")
    write("ae", "rrrrrrrr", ["$N$", r"$\epsilon$", "$d_f$", "$F$", "$M$", "queries",
                                     r"$|\hat A - A| \le \pi/M$", r"$|\hat\sigma - \sigma^H| \le \epsilon\bar\sigma$"], rows)


# ---- tab:cost (Sec. 5.5): least squares against the baseline, N = 1024 --------------------------------
def tab_cost(N=1024, rhos=(10.0, 100.0, 1e3, 1e4), eps=EPS):
    rows = []
    for rho in rhos:
        sbar = 0.25 + 0.75 / rho
        a, b = ls_cost(N, rho, eps, sbar), baseline_cost(N, rho, eps, sbar)
        assert b["toffoli"] > 100 * a["toffoli"]                             # "two orders or more"
        lab = f"${rho:g}$" if rho < 1e3 else f"$10^{{{int(np.log10(rho))}}}$"
        for name, c in (("baseline", b), ("least squares", a)):
            rows.append([lab if name == "baseline" else "", name, intx(c["d"]), fx(c["C"], 1),
                         f"${c['F']}$", intx(c["M"]), sci(c["queries_uv"]), sci(c["toffoli"]),
                         intx(c["qubits"])])
        print(f"       rho {rho:g}: LS {a}\n                BASE {b}\n                ratio {b['toffoli'] / a['toffoli']:.3g}")
    write("cost", "llrrrrrrr", [r"$\rho$", "readout", "degree", "$C$", "$F$", "$M$",
                                        r"queries to $\mathcal{U}_V$", "Toffoli", "qubits"], rows)



TABLES = {
    "ls":     (tab_ls,     "least-squares form on three cells (tab:ls, Sec. 5.1)"),
    "mesh":   (tab_mesh,   "mesh independence, square (tab:mesh, Sec. 5.2)"),
    "qiskit": (tab_qiskit, "the readout as one Qiskit circuit (tab:qiskit, Sec. 5.3)"),
    "arith":  (tab_arith,  "gate-level arithmetic U_V (tab:arith, Sec. 5.4)"),
    "ae":     (tab_ae,     "amplitude estimation (tab:ae, Sec. 5.4)"),
    "cost":   (tab_cost,   "least squares against the baseline (tab:cost, Sec. 5.5)"),
}


if __name__ == "__main__":
    argv = sys.argv[1:]
    if "--list" in argv:
        for k, (_, d) in TABLES.items():
            print(f"  {k:<8} {d}")
        raise SystemExit
    for name in [a for a in argv if not a.startswith("-")] or list(TABLES):
        fn, desc = TABLES[name]
        print(f"{name}  ({desc})")
        fn()
    print("\ndone")
